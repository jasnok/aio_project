BEGIN;

CREATE TABLE IF NOT EXISTS hotel_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id VARCHAR(50) NOT NULL REFERENCES hotels(hotel_id) ON DELETE CASCADE,
    policy_type VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    content TEXT NOT NULL,
    effective_date DATE NOT NULL DEFAULT DATE '2026-01-01',
    is_mock BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT hotel_policies_hotel_type_unique UNIQUE (hotel_id, policy_type)
);

CREATE INDEX IF NOT EXISTS idx_hotel_policies_hotel_id ON hotel_policies(hotel_id);
CREATE INDEX IF NOT EXISTS idx_hotel_policies_type ON hotel_policies(policy_type);

