BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS tour_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(30) NOT NULL,
    entity_id VARCHAR(50) NOT NULL,
    chunk_type VARCHAR(50) NOT NULL DEFAULT 'summary',
    chunk_index INTEGER NOT NULL DEFAULT 0,
    content TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    embedding_provider VARCHAR(30) NOT NULL,
    embedding_model VARCHAR(100) NOT NULL,
    embedding_dimension INTEGER NOT NULL CHECK (embedding_dimension > 0),
    embedding vector NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tour_documents_entity_type_check
        CHECK (entity_type IN ('hotel', 'attraction', 'hotel_policy')),
    CONSTRAINT tour_documents_chunk_index_check CHECK (chunk_index >= 0),
    CONSTRAINT tour_documents_embedding_identity_unique UNIQUE (
        entity_type, entity_id, chunk_type, chunk_index,
        embedding_provider, embedding_model
    )
);

CREATE INDEX IF NOT EXISTS idx_tour_documents_entity
    ON tour_documents (entity_type, entity_id);
CREATE INDEX IF NOT EXISTS idx_tour_documents_embedding_identity
    ON tour_documents (embedding_provider, embedding_model, embedding_dimension);
CREATE INDEX IF NOT EXISTS idx_tour_documents_metadata
    ON tour_documents USING gin (metadata);

COMMIT;
